import { join } from "node:path";
import { parse } from "yaml";
import { describe, expect, it } from "vitest";
import { loadSuite, parseSuite } from "../src/config.js";
import { generateSuite, todoTasks } from "../src/init.js";
import { openSession } from "../src/mcp.js";
import { ScriptedProvider } from "../src/providers/scripted.js";
import { runSuite } from "../src/runner.js";

const NOTES = join(import.meta.dirname, "..", "examples", "notes-suite.yaml");

describe("toolgrade init", () => {
  it("generates a valid suite with one task per tool and a control task, from a real server", async () => {
    const real = await loadSuite(NOTES);
    const session = await openSession(real.server);
    const yaml = generateSuite("notes", { command: "node", args: ["--import", "tsx", "server.ts"], cwd: "notes-server" }, session.tools);
    await session.close();

    const suite = parseSuite(parse(yaml), join(import.meta.dirname, "..", "examples"));
    expect(suite.tasks.map((t) => t.id)).toEqual(["search-notes", "get-note", "create-note", "delete-note", "list-tags", "control-no-tools-needed"]);
    expect(todoTasks(suite.tasks)).toHaveLength(5);
    expect(yaml).toContain("# Generated by `toolgrade init`");
  });

  it("gives colliding tool names unique task ids", () => {
    const tools = [
      { name: "a_b", inputSchema: {} },
      { name: "a-b", inputSchema: {} },
    ];
    const suite = parseSuite(parse(generateSuite("x", { url: "http://localhost:1/mcp" }, tools)), "/");
    expect(suite.tasks.map((t) => t.id)).toEqual(["a-b", "a-b-2", "control-no-tools-needed"]);
  });

  it("refuses to run a suite that still has TODO placeholders, before any model call", async () => {
    const real = await loadSuite(NOTES);
    const suite = parseSuite(parse(generateSuite("x", { url: "http://localhost:1/mcp" }, [{ name: "t", inputSchema: {} }])), "/");
    suite.server = real.server;
    const provider = new ScriptedProvider(() => ({ text: "x" }));
    await expect(runSuite(suite, { provider })).rejects.toThrow(/TODO placeholders in: t/);
    expect(provider.requests).toHaveLength(0);
    // The finished control task alone is runnable.
    await expect(runSuite(suite, { provider, filter: "control", trials: 1 })).resolves.toBeDefined();
  });
});
