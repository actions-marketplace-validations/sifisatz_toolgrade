import {
  CircleAlert,
  CircleCheck,
  CircleDashed,
  FlaskConical,
  TrendingDown,
  TrendingUp,
} from "lucide-react";
import { signedPct } from "@/lib/format";
import { cn } from "@/lib/utils";

const pill =
  "inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-xs font-medium whitespace-nowrap";

/** Status colour always travels with an icon and a label, never alone. */
export function GateBadge({
  passed,
  className,
}: {
  passed: boolean;
  className?: string;
}) {
  return passed ? (
    <span
      className={cn(
        pill,
        "border-status-good/30 bg-status-good/10 text-foreground",
        className,
      )}
    >
      <CircleCheck className="size-3.5 text-status-good" aria-hidden />
      Gate passed
    </span>
  ) : (
    <span
      className={cn(
        pill,
        "border-status-critical/30 bg-status-critical/10 text-foreground",
        className,
      )}
    >
      <CircleAlert className="size-3.5 text-status-critical" aria-hidden />
      Gate failed
    </span>
  );
}

export function SignificanceBadge({
  value,
}: {
  value: string | null | undefined;
}) {
  if (!value) return null;
  if (value === "better")
    return (
      <span className={cn(pill, "border-border text-foreground")}>
        <TrendingUp className="size-3.5 text-status-good" aria-hidden />
        Significant
      </span>
    );
  if (value === "worse")
    return (
      <span className={cn(pill, "border-border text-foreground")}>
        <TrendingDown className="size-3.5 text-status-critical" aria-hidden />
        Significantly worse
      </span>
    );
  return (
    <span className={cn(pill, "border-border text-muted-foreground")}>
      <CircleDashed className="size-3.5" aria-hidden />
      Not significant
    </span>
  );
}

/** Signed lift in percentage points; direction icon carries meaning, text stays in ink. */
export function Lift({
  value,
  className,
}: {
  value: number | null | undefined;
  className?: string;
}) {
  if (value === null || value === undefined)
    return <span className="text-muted-foreground">-</span>;
  const Icon = value > 0 ? TrendingUp : value < 0 ? TrendingDown : null;
  return (
    <span
      className={cn("inline-flex items-center gap-1 tabular-nums", className)}
    >
      {Icon && (
        <Icon
          className={cn(
            "size-3.5",
            value > 0 ? "text-status-good" : "text-status-critical",
          )}
          aria-hidden
        />
      )}
      {signedPct(value)}
    </span>
  );
}

export function DemoBadge() {
  return (
    <span
      className={cn(pill, "border-border text-muted-foreground")}
      title="Generated by the ToolGrade engine against the real example server with a simulated agent"
    >
      <FlaskConical className="size-3.5" aria-hidden />
      Demo data
    </span>
  );
}
